CREATE OR REPLACE FUNCTION is_allowed_email()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM allowed_email_suffixes s
    WHERE lower(
      right(
        coalesce(current_setting('request.jwt.claims', true)::jsonb ->> 'email', ''),
        length(s.suffix)
      )
    ) = lower(s.suffix)
  );
$$;


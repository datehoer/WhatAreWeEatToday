CREATE OR REPLACE FUNCTION get_all_tags()
RETURNS TABLE (
    tag TEXT,
    count BIGINT
)
LANGUAGE sql
AS $$
    SELECT 
        TRIM(t) AS tag,     -- 去除前后空格
        COUNT(*) AS count
    FROM shops, 
    unnest(string_to_array(tag, ';')) AS t -- 直接拆分
    WHERE 
        tag IS NOT NULL 
        AND TRIM(t) <> '' -- 确保拆分后不是空字符串
    GROUP BY TRIM(t)
    ORDER BY count DESC, tag ASC
    LIMIT 50; -- 建议加个限制，只取最热门的50个，防止前端渲染太多卡顿
$$;


-- 修改后的查询函数，增加了 filter_tag 参数
CREATE OR REPLACE FUNCTION get_shops_fixed(
  center_lat float, 
  center_lng float, 
  radius_meters int default 2000, 
  limit_count int default 50,
  filter_tag text default null -- 新增参数，默认为空
)
RETURNS TABLE (
  id bigint, 
  name text, 
  rating numeric, 
  avg_price numeric, 
  tag text,
  logo text,
  dist_meters float
)
LANGUAGE sql
AS $$
  SELECT 
    id, name, rating, avg_price, tag, logo,
    st_distance(location, st_point(center_lng, center_lat)::geography) as dist_meters
  FROM shops
  WHERE 
    st_dwithin(location, st_point(center_lng, center_lat)::geography, radius_meters)
    AND (
        filter_tag IS NULL -- 如果没传标签，就不过滤
        OR 
        tag ILIKE '%' || filter_tag || '%' -- 如果传了，就模糊匹配 (包含该标签)
    )
  ORDER BY 
    dist_meters ASC
  LIMIT limit_count;
$$;



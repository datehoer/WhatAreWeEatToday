CREATE EXTENSION IF NOT EXISTS postgis;
CREATE TABLE shops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 自增ID
    gaode_id TEXT UNIQUE,     -- 高德原始ID (防止重复导入)
    name TEXT NOT NULL,       -- 店名
    
    -- 核心：地理位置 (点坐标, SRID 4326 是 GPS 标准)
    location GEOGRAPHY(POINT, 4326), 
    
    rating NUMERIC DEFAULT 0, -- 评分 (如 4.5)
    avg_price NUMERIC,        -- 人均价格
    tag TEXT,                 -- 标签 (如 "川菜;火锅")
    logo TEXT,                -- 图片链接
    
    -- 可选：存更多详情，如营业时间
    deepinfo JSONB            
);

-- 创建地理索引 (这一步对性能至关重要！)
CREATE INDEX idx_shops_location ON shops USING GIST (location);

CREATE TABLE vote_rooms (
    room_code TEXT PRIMARY KEY, -- 房间号，例如 "8848" 或 "x7z9a"
    
    -- 核心：候选人快照
    -- 数据结构: [{"id": 1, "name": "麦当劳", "vote_count": 0}, ...]
    candidates JSONB NOT NULL,
    
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE vote_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    room_code TEXT REFERENCES vote_rooms(room_code) ON DELETE CASCADE, -- 关联房间
    shop_id BIGINT,  -- 投给了哪个店
    
    -- 核心：防刷票机制
    -- 前端在 LocalStorage 生成一个随机 UUID 作为 voter_id
    voter_id TEXT NOT NULL,
    
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),

    -- 约束：同一个房间，同一个人，只能投一票
    UNIQUE(room_code, voter_id)
);

CREATE OR REPLACE FUNCTION get_nearby_shops(
    lat FLOAT,           -- 中心纬度
    lng FLOAT,           -- 中心经度
    radius_meters INT DEFAULT 2000, -- 搜索半径 (默认2公里)
    limit_count INT DEFAULT 50      -- 返回数量
)
RETURNS TABLE (
    id BIGINT,
    name TEXT,
    rating NUMERIC,
    avg_price NUMERIC,
    tag TEXT,
    logo TEXT,
    dist_meters FLOAT    -- 计算出的距离
)
LANGUAGE sql
AS $$
    SELECT 
        id, name, rating, avg_price, tag, logo,
        -- 计算距离 (单位: 米)
        ST_Distance(location, ST_Point(lng, lat)::geography) AS dist_meters
    FROM 
        shops
    WHERE 
        -- 筛选半径内的点
        ST_DWithin(location, ST_Point(lng, lat)::geography, radius_meters)
    ORDER BY 
        dist_meters ASC -- 按距离排序
    LIMIT 
        limit_count;
$$;

-- 获取所有标签及其统计
CREATE OR REPLACE FUNCTION get_all_tags()
RETURNS TABLE (
    tag TEXT,
    count BIGINT
)
LANGUAGE sql
AS $$
    SELECT
        TRIM(unnest) AS tag,
        COUNT(*) AS count
    FROM (
        SELECT regexp_split_to_array(tag, ';') AS tags_array
        FROM shops
        WHERE tag IS NOT NULL AND tag != ''
    ) subquery,
    unnest(tags_array)
    GROUP BY tag
    ORDER BY count DESC, tag ASC;
$$;


DROP FUNCTION IF EXISTS get_shops_with_tag_filters(double precision, double precision, integer, integer, integer, text[], text[]);

-- 支持多标签包含/排除的查询函数
CREATE OR REPLACE FUNCTION get_shops_with_tag_filters(
  center_lat float,
  center_lng float,
  radius_meters int default 2000,
  offset_count int default 0,
  limit_count int default 50,
  include_tags text[] default null,  -- 包含的标签数组（任一匹配即可）
  exclude_tags text[] default null  -- 排除的标签数组（全部不匹配）
)
RETURNS TABLE (
  id bigint,
  name text,
  rating numeric,
  avg_price numeric,
  tag text,
  logo text,
  deepinfo text,
  dist_meters float
)
LANGUAGE sql
AS $$
  SELECT
    id, name, rating, avg_price, tag, logo, deepinfo,
    st_distance(location, st_point(center_lng, center_lat)::geography) as dist_meters
  FROM shops
  WHERE
    st_dwithin(location, st_point(center_lng, center_lat)::geography, radius_meters)
    -- 包含标签过滤：如果有 include_tags，店铺标签必须至少包含其中一个
    AND (
      include_tags IS NULL
      OR EXISTS (
        SELECT 1 FROM unnest(string_to_array(tag, ';')) AS shop_tag
        WHERE TRIM(shop_tag) = ANY(include_tags)
      )
    )
    -- 排除标签过滤：如果有 exclude_tags，店铺标签不能包含其中任何一个
    AND (
      exclude_tags IS NULL
      OR NOT EXISTS (
        SELECT 1 FROM unnest(string_to_array(tag, ';')) AS shop_tag
        WHERE TRIM(shop_tag) = ANY(exclude_tags)
      )
    )
  ORDER BY
    dist_meters ASC
  OFFSET offset_count
  LIMIT limit_count;
$$;
